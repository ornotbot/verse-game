// Build worker/wordlist.js from data/ (run after editing data/*.txt).
const fs = require('fs');
const allowed = fs.readFileSync('data/allowed-guesses.txt','utf8').trim().split('\n').filter(Boolean);
const answers = fs.readFileSync('data/answers.txt','utf8').trim().split('\n').filter(Boolean);
const out = '// GENERATED by scripts/build-wordlist.js - do not edit\n'
  + 'export const ALLOWED = ' + JSON.stringify(allowed) + ';\n'
  + 'export const ANSWERS = ' + JSON.stringify(answers) + ';\n';
fs.writeFileSync('worker/wordlist.js', out);
console.log('wordlist.js:', allowed.length, 'allowed,', answers.length, 'answers');
